export interface ShapePiece { id: string; index: number; label: string; roleName: string; x: number; y: number; length: number; width: number; rotation: number; color: string; toneType: 'luz'|'profundo'; hemisphere: 'superior'|'inferior'; opacity: number; visible: boolean; locked: boolean; zIndex?: number; }

export function createShape(index: number, x: number, y: number, length: number, rotation: number, color: string, toneType: 'luz'|'profundo', roleName: string): ShapePiece {
  return {
    id: 'forma-' + index.toString().padStart(2, '0'),
    index,
    label: 'Forma ' + index.toString().padStart(2, '0'),
    roleName,
    x,
    y,
    length,
    width: 67,
    rotation,
    color,
    toneType,
    hemisphere: index <= 6 ? 'superior' : 'inferior',
    opacity: 1,
    visible: true,
    locked: false,
  };
}

