import { HMAPiece, HMAPreset, ShapeType } from '../types/hma';

export function mapShapePieceToHMAPiece(p: ShapePiece): HMAPiece {
  const isPoint = (p.length === 67 && p.width === 67) || (Math.abs(p.length - p.width) < 1);
  let shapeType: ShapeType = 'P3_rect2x1';
  if (isPoint) {
    shapeType = 'P10_point';
  } else if (p.length >= 201) {
    shapeType = 'P11_capsule3x1';
  } else if (p.length <= 67) {
    shapeType = 'P2_square';
  }

  return {
    id: p.id,
    shapeType,
    name: p.roleName || `Pieza ${p.index}`,
    category: p.hemisphere === 'superior' ? 'upper' : 'base',
    x: p.x - 413,
    y: p.y - 413,
    rotation: p.rotation,
    widthM: (p.width || 67) / 67, // 1M thickness across
    heightM: (p.length || 67) / 67, // length along capsule axis
    scaleX: 1,
    scaleY: 1,
    color: p.color,
    opacity: p.opacity !== undefined ? p.opacity : 1,
    visible: p.visible !== undefined ? p.visible : true,
    locked: p.locked !== undefined ? p.locked : false,
    zIndex: p.zIndex !== undefined ? p.zIndex : p.index
  };
}

