export function getShapeSvgPath(type: ShapeType, w: number, h: number): string {
  // Since all official templates now use rectangles/capsules, we generate a rounded rectangle path.
  // M x,y + A (arcs) or just use standard SVG <rect> logic if it was a <rect>, 
  // but since we must return a `d` path for <path>:
  const r = 33.5;
  // A rounded rect path:
  // Move to top-left + radius
  // Line to top-right - radius, Arc to top-right
  // Line to bottom-right - radius, Arc to bottom-right
  // Line to bottom-left + radius, Arc to bottom-left
  // Line to top-left + radius, Arc to top-left
  
  if (type.includes('rect') || type.includes('diagonal') || type.includes('point') || type.includes('capsule') || type.includes('bar') || type.includes('square')) {
     return `M ${-w/2 + r},${-h/2} L ${w/2 - r},${-h/2} A ${r},${r} 0 0 1 ${w/2},${-h/2 + r} L ${w/2},${h/2 - r} A ${r},${r} 0 0 1 ${w/2 - r},${h/2} L ${-w/2 + r},${h/2} A ${r},${r} 0 0 1 ${-w/2},${h/2 - r} L ${-w/2},${-h/2 + r} A ${r},${r} 0 0 1 ${-w/2 + r},${-h/2} Z`;
  }
  
  // Fallback simple rect
  return `M ${-w/2},${-h/2} L ${w/2},${-h/2} L ${w/2},${h/2} L ${-w/2},${h/2} Z`;
}
